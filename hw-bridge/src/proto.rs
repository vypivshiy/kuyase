pub fn push_varint(buf: &mut Vec<u8>, mut val: u64) {
    loop {
        let mut byte = (val & 0x7f) as u8;
        val >>= 7;
        if val != 0 {
            byte |= 0x80;
        }
        buf.push(byte);
        if val == 0 {
            break;
        }
    }
}

pub fn push_varint_field(buf: &mut Vec<u8>, field_num: u32, val: u64) {
    let tag = (field_num as u64) << 3;
    push_varint(buf, tag);
    push_varint(buf, val);
}

pub fn push_len_delimited(buf: &mut Vec<u8>, field_num: u32, payload: &[u8]) {
    let tag = ((field_num as u64) << 3) | 2;
    push_varint(buf, tag);
    push_varint(buf, payload.len() as u64);
    buf.extend_from_slice(payload);
}

pub fn push_f64_field(buf: &mut Vec<u8>, field_num: u32, val: f64) {
    let tag = ((field_num as u64) << 3) | 1;
    push_varint(buf, tag);
    buf.extend_from_slice(&val.to_le_bytes());
}

pub fn push_f32_field(buf: &mut Vec<u8>, field_num: u32, val: f32) {
    let tag = ((field_num as u64) << 3) | 5;
    push_varint(buf, tag);
    buf.extend_from_slice(&val.to_le_bytes());
}

pub fn frame_quasar_packet(payload: &[u8]) -> Vec<u8> {
    let mut framed = Vec::with_capacity(4 + payload.len());
    framed.extend_from_slice(&(payload.len() as u32).to_le_bytes());
    framed.extend_from_slice(payload);
    framed
}

/// Builds a `QuasarMessage` carrying `AliceState` (type `3`) in the requested wire format
/// (`LegacyDirect` field `3` or `Envelope252` `payload = 252, type = 253 (3)`).
pub fn build_alice_state_event_with_format(
    phase: Option<u64>,
    transcript: &str,
    request_id: &str,
    final_flag: bool,
    wire_format: QuasarWireFormat,
) -> Vec<u8> {
    let state = ProtoAliceState {
        state: phase,
        recognized_phrase: if transcript.is_empty() {
            None
        } else {
            Some(transcript.to_string())
        },
        voice_power: None,
        request_id: if request_id.is_empty() {
            None
        } else {
            Some(request_id.to_string())
        },
        has_speech: None,
        doa_angle: None,
        request_state_final: if final_flag { Some(true) } else { None },
    };
    QuasarMessage::encode_with_format(
        QuasarMessageType::ALICE_STATE,
        &state.to_bytes(),
        wire_format,
    )
}

/// `QuasarMessage{3: AliceState{2: transcript, 7: request_id, 15: {2: final}}}`
