pub fn build_yio_audio_frame_with_format(
    doa_deg: f32,
    target_rms: u16,
    seq: u64,
    wire_format: QuasarWireFormat,
) -> Vec<u8> {
    // One frame is emitted every 40 ms: at 16 kHz this is 640 samples.
    let n_samples = 640usize;
    let mut base_samples = vec![0i16; n_samples + 16];
    let amp = ((target_rms as f32) * 1.414).min(28_000.0);
    for (i, slot) in base_samples.iter_mut().enumerate() {
        let t = (seq * n_samples as u64 + i as u64) as f32;
        // Broadband multi-tone signal with rich high-frequency slope for TDOA cross-correlation
        let v = (t * 0.42).sin() * 0.55 + (t * 1.13).cos() * 0.30 + (t * 2.31).sin() * 0.15;
        *slot = (v * amp) as i16;
    }

    let rad = doa_deg.to_radians();
    let cos_a = rad.cos();
    let sin_a = rad.sin();

    // TDOA sample shifts at step=2 (lag_samples = lag * 2 in [-4..+4])
    let shift_02 = (cos_a * 4.0).round() as isize;
    let shift_13 = (sin_a * 4.0).round() as isize;

    let gains = [
        (1.0 + 0.45 * cos_a).max(0.2),
        (1.0 + 0.45 * sin_a).max(0.2),
        (1.0 - 0.45 * cos_a).max(0.2),
        (1.0 - 0.45 * sin_a).max(0.2),
    ];
    let offsets: [isize; 4] = [
        8,
        8,
        (8 - shift_02).clamp(2, 14),
        (8 - shift_13).clamp(2, 14),
    ];

    let names = ["raw_mic_0", "raw_mic_1", "raw_mic_2", "raw_mic_3"];
    let mut channels = Vec::with_capacity(5);

    for m in 0..4 {
        let mut pcm = Vec::with_capacity(n_samples * 2);
        let off = offsets[m] as usize;
        for i in 0..n_samples {
            let s = ((base_samples[off + i] as f32) * gains[m]).clamp(-32767.0, 32767.0) as i16;
            pcm.extend_from_slice(&s.to_le_bytes());
        }
        channels.push(IOAudioChannelData {
            channel_type: IOAudioChannelData::TYPE_RAW_MIC,
            name: names[m].to_string(),
            data: pcm,
            is_for_recognition: false,
            legacy_doa_float: None,
            doa_angle: None,
            sample_rate: 16000,
            format: IOAudioChannelData::FORMAT_PCM,
        });
    }

    let mut vqe_pcm = Vec::with_capacity(n_samples * 2);
    for i in 0..n_samples {
        vqe_pcm.extend_from_slice(&base_samples[8 + i].to_le_bytes());
    }
    channels.push(IOAudioChannelData {
        channel_type: IOAudioChannelData::TYPE_VQE_OMNI,
        name: "vqe_0".to_string(),
        data: vqe_pcm,
        is_for_recognition: true,
        legacy_doa_float: Some(doa_deg),
        doa_angle: Some(doa_deg as f64),
        sample_rate: 16000,
        format: IOAudioChannelData::FORMAT_PCM,
    });

    let channels_data = IOAudioChannelsData { channels };
    let qmsg = QuasarMessage::encode_with_format(
        QuasarMessageType::IO_AUDIO_CHANNELS_DATA,
        &channels_data.to_bytes(),
        wire_format,
    );

    frame_quasar_packet(&qmsg)
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PbField<'a> {
    Varint(u64),
    Fixed64(u64),
    Bytes(&'a [u8]),
    Fixed32(u32),
}

pub fn read_pb_varint(buf: &[u8], pos: &mut usize) -> Result<u64, &'static str> {
    let mut val = 0u64;
    let mut shift = 0u32;
    while *pos < buf.len() {
        let b = buf[*pos];
        *pos += 1;
        val |= ((b & 0x7f) as u64) << shift;
        if (b & 0x80) == 0 {
            return Ok(val);
        }
        shift += 7;
        if shift >= 64 {
            return Err("varint overflow");
        }
    }
    Err("truncated varint")
}

pub fn next_pb_field<'a>(
    buf: &'a [u8],
    pos: &mut usize,
) -> Result<Option<(u32, PbField<'a>)>, &'static str> {
    if *pos >= buf.len() {
        return Ok(None);
    }
    let tag = read_pb_varint(buf, pos)?;
    let field_num = (tag >> 3) as u32;
    let wire_type = (tag & 0x07) as u8;
    if field_num == 0 {
        return Err("invalid field number 0");
    }
    match wire_type {
        0 => Ok(Some((field_num, PbField::Varint(read_pb_varint(buf, pos)?)))),
        1 => {
            if *pos + 8 > buf.len() {
                return Err("truncated fixed64");
            }
            let mut arr = [0u8; 8];
            arr.copy_from_slice(&buf[*pos..*pos + 8]);
            *pos += 8;
            Ok(Some((field_num, PbField::Fixed64(u64::from_le_bytes(arr)))))
        }
        2 => {
            let len = read_pb_varint(buf, pos)? as usize;
            if *pos + len > buf.len() {
                return Err("truncated length-delimited field");
            }
            let slice = &buf[*pos..*pos + len];
            *pos += len;
            Ok(Some((field_num, PbField::Bytes(slice))))
        }
        5 => {
            if *pos + 4 > buf.len() {
                return Err("truncated fixed32");
            }
            let mut arr = [0u8; 4];
            arr.copy_from_slice(&buf[*pos..*pos + 4]);
            *pos += 4;
            Ok(Some((field_num, PbField::Fixed32(u32::from_le_bytes(arr)))))
        }
        _ => Err("unsupported wire type"),
    }
}

#[derive(Debug, PartialEq, Eq)]
pub enum DecodedRemoting {
    CancelDialog,
    StopTts,
    StartVocalize(String),
    StartConversation,
    ToggleConversation,
    StartRequestText(String),
    AliceMethod(u64),
    PlaybackControl(u64),
    DeviceState { mics_muted: Option<bool> },
    OtherCapability { object_id: String, method_field: u32 },
}

/// Decodes a `QuasarMessage` carrying `Remoting` (`type = 210`) from either legacy direct-field
/// (`<= 0.367`) or modern `LITE_RUNTIME` envelope (`payload = 252, type = 253` in `>= 0.368`)
/// wire format, returning both the decoded command and the peer's wire format.
pub fn decode_quasar_remoting_packet_with_format(
    payload: &[u8],
) -> Result<(DecodedRemoting, QuasarWireFormat), String> {
    let qmsg = QuasarMessage::decode(payload)?;
    let rem_buf = qmsg
        .find_payload(QuasarMessageType::REMOTING)
        .ok_or_else(|| "missing QuasarMessage.remoting (field 210)".to_string())?;
    let rem = Remoting::decode(rem_buf)?;
    let wf = qmsg.wire_format;

    if rem.remote_object_id == "PlaybackControlCapability" {
        if let Some(pb) = rem.playback_control_capability_method {
            return Ok((
                DecodedRemoting::PlaybackControl(pb.method.unwrap_or(0) as u64),
                wf,
            ));
        }
        if let Some(mf) = rem.other_method_field {
            return Ok((
                DecodedRemoting::OtherCapability {
                    object_id: rem.remote_object_id,
                    method_field: mf,
                },
                wf,
            ));
        }
        return Err(
            "PlaybackControlCapability missing playback_control_capability_method (field 13)"
                .to_string(),
        );
    }

    if rem.remote_object_id == "DeviceStateCapability" {
        if let Some(ds) = rem.device_state_capability_method {
            return Ok((
                DecodedRemoting::DeviceState {
                    mics_muted: ds.effective_mics_muted(),
                },
                wf,
            ));
        }
        if let Some(mf) = rem.other_method_field {
            return Ok((
                DecodedRemoting::OtherCapability {
                    object_id: rem.remote_object_id,
                    method_field: mf,
                },
                wf,
            ));
        }
    }

    if rem.remote_object_id == "AliceCapability" {
        if let Some(alice_m) = rem.alice_capability_method {
            let decoded = match alice_m.method {
                Some(AliceCapabilityMethod::START_REQUEST) => {
                    if let Some(text) = alice_m
                        .vins_request
                        .as_ref()
                        .and_then(|vr| vr.extract_text_input_query())
                    {
                        DecodedRemoting::StartRequestText(text)
                    } else {
                        DecodedRemoting::AliceMethod(AliceCapabilityMethod::START_REQUEST)
                    }
                }
                Some(
                    AliceCapabilityMethod::CANCEL_DIALOG
                    | AliceCapabilityMethod::STOP_CONVERSATION
                    | AliceCapabilityMethod::CANCEL_DIALOG_AND_CLEAR_QUEUE,
                ) => DecodedRemoting::CancelDialog,
                Some(AliceCapabilityMethod::START_CONVERSATION) => {
                    DecodedRemoting::StartConversation
                }
                Some(AliceCapabilityMethod::TOGGLE_CONVERSATION) => {
                    DecodedRemoting::ToggleConversation
                }
                Some(AliceCapabilityMethod::STOP_TTS) => DecodedRemoting::StopTts,
                Some(AliceCapabilityMethod::START_VOCALIZE) => {
                    let vocalize_text = alice_m
                        .vocalize_directive
                        .map(|vd| vd.text)
                        .unwrap_or_default();
                    if vocalize_text.is_empty() {
                        return Err(
                            "START_VOCALIZE (18) missing vocalize_directive.Text (field 13.1)"
                                .to_string(),
                        );
                    }
                    DecodedRemoting::StartVocalize(vocalize_text)
                }
                Some(m) => DecodedRemoting::AliceMethod(m),
                None => return Err("AliceCapabilityMethod missing method enum (field 1)".to_string()),
            };
            return Ok((decoded, wf));
        }
        if let Some(mf) = rem.other_method_field {
            return Ok((
                DecodedRemoting::OtherCapability {
                    object_id: rem.remote_object_id,
                    method_field: mf,
                },
                wf,
            ));
        }
        return Err("AliceCapability missing alice_capability_method (field 8)".to_string());
    }

    if !rem.remote_object_id.is_empty() {
        if let Some(mf) = rem.other_method_field {
            return Ok((
                DecodedRemoting::OtherCapability {
                    object_id: rem.remote_object_id,
                    method_field: mf,
                },
                wf,
            ));
        }
    }

    Err(format!(
        "unsupported or missing Remoting.remote_object_id (field 7): '{}'",
        rem.remote_object_id
    ))
}

#[derive(Debug, PartialEq, Eq)]
pub enum DecodedIoHubPacket {
    ExternalDirectives(String),
    IoControlField(u32),
    RetrieveStateHandshake,
    ServiceReady(String),
    IoEvent,
}

/// Strict decoder for `QuasarMessage` on `iohub_services` (`:9903`).
/// Supports `io_control` (`88`), `io_hub_message` (`183`), `service_name_ready` (`157`), and
/// `io_event` (`85`) in both legacy direct-field (`<= 0.367`) and `252/253` envelope (`>= 0.368`)
/// wire formats.
pub fn decode_quasar_io_control_packet(payload: &[u8]) -> Result<DecodedIoHubPacket, String> {
    let qmsg = QuasarMessage::decode(payload)?;

    if let Some(ctrl_buf) = qmsg.find_payload(QuasarMessageType::IO_CONTROL) {
        let ctrl = IOControlCommand::decode(ctrl_buf)?;
        if let Some(ext) = ctrl.external_directives {
            return Ok(DecodedIoHubPacket::ExternalDirectives(ext));
        }
        if let Some(f) = ctrl.first_field_num {
            return Ok(DecodedIoHubPacket::IoControlField(f));
        }
        return Err(
            "IOControlCommand (field 88) is empty (missing external_directives field 95)"
                .to_string(),
        );
    }

    if qmsg
        .find_payload(QuasarMessageType::IO_HUB_MESSAGE)
        .is_some()
    {
        return Ok(DecodedIoHubPacket::RetrieveStateHandshake);
    }

    if let Some(b) = qmsg.find_payload(QuasarMessageType::SERVICE_NAME_READY) {
        return Ok(DecodedIoHubPacket::ServiceReady(
            String::from_utf8_lossy(b).into_owned(),
        ));
    }

    if qmsg
        .entries
        .iter()
        .any(|(fnum, _)| (1..=300).contains(fnum))
    {
        return Ok(DecodedIoHubPacket::IoEvent);
    }

    Err("missing QuasarMessage.io_control (88) or io_hub_message (183)".to_string())
}

