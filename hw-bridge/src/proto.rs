    #[test]
    fn test_capability_handshakes_round_trip() {
        for wf in [
            QuasarWireFormat::LegacyDirect,
            QuasarWireFormat::Envelope252,
        ] {
            let framed_ep = build_endpoint_storage_add_endpoint_packet("EMU0001", wf);
            let ep_len = u32::from_le_bytes(framed_ep[..4].try_into().unwrap()) as usize;
            assert_eq!(ep_len + 4, framed_ep.len());
            let qmsg = QuasarMessage::decode(&framed_ep[4..]).unwrap();
            assert_eq!(qmsg.wire_format, wf);
            let rem =
                Remoting::decode(qmsg.find_payload(QuasarMessageType::REMOTING).unwrap()).unwrap();
            assert_eq!(rem.remote_object_id, "EndpointStorage_");
            let esm = rem.endpoint_storage_method.unwrap();
            assert_eq!(esm.method, Some(EndpointStorageMethod::ADD_ENDPOINT));
            assert_eq!(esm.storage_name.as_deref(), Some("aliced"));
            assert_eq!(esm.endpoints.len(), 1);
            let ep = &esm.endpoints[0];
            assert_eq!(ep.endpoint.as_ref().unwrap().id, "EMU0001");
            assert_eq!(
                ep.endpoint.as_ref().unwrap().endpoint_type,
                TEndpoint::SPEAKER_ENDPOINT_TYPE
            );
            assert!(ep
                .capabilities
                .iter()
                .all(|ch| ch.storage_name.as_deref() == Some("aliced")));
            assert!(ep.capabilities.iter().any(|ch| {
                ch.capability
                    .as_ref()
                    .and_then(|c| c.id.as_deref())
                    == Some("PlaybackControlCapability")
            }));

            let framed_fp = build_file_player_handshake_response_packet(wf);
            let fp_len = u32::from_le_bytes(framed_fp[..4].try_into().unwrap()) as usize;
            assert_eq!(fp_len + 4, framed_fp.len());
            let qmsg_fp = QuasarMessage::decode(&framed_fp[4..]).unwrap();
            assert_eq!(qmsg_fp.wire_format, wf);
            let rem_fp =
                Remoting::decode(qmsg_fp.find_payload(QuasarMessageType::REMOTING).unwrap())
                    .unwrap();
            assert_eq!(rem_fp.remote_object_id, "FilePlayerCapability");
            assert!(
                rem_fp
                    .file_player_capability_events_method
                    .unwrap()
                    .handshake_response
            );
        }
    }
