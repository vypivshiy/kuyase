//! Unified multi-generation Quasar Stack Protobuf codec and domain facade.
//!
//! ### Multi-Generation Wire Format Equivalence (`<= 0.367` vs `>= 0.368`)
//!
//! Across all Yandex Station firmware releases from 2020 (`1.266.4.40`) and 2025 (`0.13.1.36`)
//! through 2026 (`0.368+`, `0.369.1.*`, `0.373.1.13`), local Quasar IPC services (`aliced` `:9875`,
//! `yio_audio` `:9850`, `iohub_services` `:9903`, `glagold` `:9899`) frame messages as
//! `[u32_le payload_len][QuasarMessage protobuf]`, with two wire encodings for `QuasarMessage`:
//!
//! ```text
//! Legacy wire format (1.266 / 0.13 / <=0.367):
//!   QuasarMessage { <type_id>: <inner_protobuf_bytes> }
//!
//! Modern LITE_RUNTIME envelope format (>=0.368 / 0.369 / 0.373):
//!   QuasarMessage {
//!     request_id = 1 (optional string),
//!     payload    = 252 (bytes, wire tag = 0xe2 0x0f: serialized inner message or raw UTF-8 string),
//!     type       = 253 (varint, wire tag = 0xe8 0x0f: QuasarMessage::Type == legacy <type_id>)
//!   }
//! ```
//!
//! The domain modules (`quasar_root`, `remoting`, `alice`, `iohub`, `glagol`) are generated by
//! `scripts/gen_quasar_proto.py` without external protobuf crate dependencies.

